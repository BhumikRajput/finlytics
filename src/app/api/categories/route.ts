import { prisma } from "@/lib/prisma";
import { getCurrentUserId } from "@/lib/current-user";
import { badRequest, conflict, isUniqueViolation, readJson, unauthorized } from "@/lib/api-helpers";
import { parseNewCategory, toApiCategory } from "@/lib/categories-api";
import { ensureCategories } from "@/lib/categories-server";

export const dynamic = "force-dynamic";

// The signed-in user's categories, in display order. The first call for a user also
// creates their default categories, so this GET can write and uses the strict check.
export async function GET() {
  const userId = await getCurrentUserId(); // strict
  if (!userId) return unauthorized();

  await ensureCategories(userId);

  const rows = await prisma.category.findMany({
    where: { userId },
    orderBy: [{ position: "asc" }, { value: "asc" }],
  });
  return Response.json(rows.map(toApiCategory));
}

// Add one custom category. The key (`value`) is generated by the client with slugify(),
// like transaction ids, so the optimistic row in the UI and the database row match.
export async function POST(req: Request) {
  const userId = await getCurrentUserId(); // strict
  if (!userId) return unauthorized();

  const parsed = parseNewCategory(await readJson(req));
  if (!parsed.ok) return badRequest(parsed.error);
  const c = parsed.value;

  // If this is the user's very first request, the defaults must exist before this
  // category does, otherwise the lazy creation in GET would think they were set up.
  await ensureCategories(userId);

  const last = await prisma.category.aggregate({ where: { userId }, _max: { position: true } });

  try {
    const row = await prisma.category.create({
      data: {
        userId,
        value: c.value,
        label: c.label,
        kind: c.kind,
        iconName: c.iconName,
        iconBg: c.iconBg,
        iconColor: c.iconColor,
        color: c.color,
        custom: true,
        position: (last._max.position ?? -1) + 1,
      },
    });
    return Response.json(toApiCategory(row), { status: 201 });
  } catch (e) {
    if (isUniqueViolation(e)) return conflict("A category with this key already exists.");
    throw e;
  }
}
