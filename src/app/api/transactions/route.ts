import { prisma } from "@/lib/prisma";
import { getCurrentUserId, getSessionUserId } from "@/lib/current-user";
import {
  badRequest,
  conflict,
  isUniqueViolation,
  readJson,
  toCents,
  unauthorized,
} from "@/lib/api-helpers";
import {
  SIGN_ERROR,
  parseNewTransaction,
  signMatchesType,
  toApiTransaction,
} from "@/lib/transactions-api";

export const dynamic = "force-dynamic";

// Every user's list, newest first. Read-only, so the cheap session check is enough.
export async function GET() {
  const userId = await getSessionUserId();
  if (!userId) return unauthorized();

  const rows = await prisma.transaction.findMany({
    where: { userId },
    orderBy: [{ date: "desc" }, { createdAt: "desc" }],
  });
  return Response.json(rows.map(toApiTransaction));
}

// Add one transaction. The id is generated by the client (crypto.randomUUID) so the
// optimistic row in the UI and the database row share the same id.
export async function POST(req: Request) {
  const userId = await getCurrentUserId(); // strict
  if (!userId) return unauthorized();

  const parsed = parseNewTransaction(await readJson(req));
  if (!parsed.ok) return badRequest(parsed.error);
  const t = parsed.value;

  const amountCents = toCents(t.amount);
  if (!signMatchesType(t.type, amountCents)) return badRequest(SIGN_ERROR);

  try {
    const row = await prisma.transaction.create({
      data: {
        id: t.id,
        userId,
        name: t.name,
        note: t.note,
        date: t.date,
        amountCents,
        type: t.type,
        category: t.category,
      },
    });
    return Response.json(toApiTransaction(row), { status: 201 });
  } catch (e) {
    if (isUniqueViolation(e)) return conflict("A transaction with this id already exists.");
    throw e;
  }
}
